"""
================================================================================
CONFIG — Бүх hyperparameter, path-уудыг нэг газар цуглуулсан
================================================================================
Энэ файлыг өөрчилснөөр бусад файлууд автоматаар шинэ тохиргоог ашиглана.
"""

from dataclasses import dataclass, field, asdict
from pathlib import Path
from typing import Tuple


@dataclass
class CFG:
    # ========================================================================
    # ЗАМ
    # ========================================================================
    # Татаж авсан 4 dataset-ийн root хавтас
    data_root: str = './datasets'
    
    # build_dataset.py-ийн гаргадаг CSV-ын зам
    train_csv: str = './data_train.csv'
    test_csv: str  = './data_test.csv'
    
    # Checkpoint, log хадгалах хавтас
    save_dir: str = './checkpoints'
    
    # ========================================================================
    # DATASET HOLD-OUT
    # ========================================================================
    test_ratio: float = 0.15        # 15% test (сургалтад огт ороохгүй)
    seed: int = 42                  # reproducibility-ийн seed
    
    # ========================================================================
    # MODEL
    # ========================================================================
    # timm-ийн ConvNeXt-Base @ 384, ImageNet-22k-аар pretrained
    model_name: str = 'convnext_base.fb_in22k_ft_in1k_384'
    dropout: float = 0.2
    drop_path_rate: float = 0.2
    
    # ========================================================================
    # ЗУРГИЙН ХЭМЖЭЭ
    # ========================================================================
    img_size: int = 384
    
    # ========================================================================
    # 16-BIT ЗУРАГ (GRAZPEDWRI)
    # ========================================================================
    # Window/level normalization-д ашиглах percentile
    # Доод p1%, дээд p99% хэсгийг тасалж 8-bit рүү map хийнэ
    wl_p_low: float = 1.0
    wl_p_high: float = 99.0
    
    # ========================================================================
    # СУРГАЛТ
    # ========================================================================
    n_folds: int = 3                # 3-fold CV (10 цагт багтахын тулд)
    epochs: int = 12                # Fold тус бүрт 12 epoch
    batch_size: int = 32            # A6000 48GB-д ConvNeXt-Base @ 384
    accumulate: int = 2             # Effective batch = 64
    grad_clip: float = 1.0
    num_workers: int = 8
    
    # ========================================================================
    # OPTIMIZER (AdamW + Layer-wise LR decay)
    # ========================================================================
    lr_head: float = 5e-4
    lr_backbone: float = 5e-5
    layer_decay: float = 0.75       # Backbone-ийн доод layer-ийн LR-ийг бууруулах
    weight_decay: float = 0.02
    warmup_epochs: int = 2
    
    # ========================================================================
    # LOSS
    # ========================================================================
    # pos_weight-ийг build_dataset.py-аас бодит датан дээр автоматаар тооцох
    # Энд default value байгаа боловч сургалтын үед автоматаар орлогдоно
    pos_weight: float = 4.0
    label_smoothing: float = 0.05
    
    # ========================================================================
    # AUGMENTATION
    # ========================================================================
    mixup_alpha: float = 0.2
    cutmix_alpha: float = 1.0
    mix_prob: float = 0.5
    
    # ========================================================================
    # EMA (Exponential Moving Average)
    # ========================================================================
    ema_decay: float = 0.9995
    
    # ========================================================================
    # TTA (Test-Time Augmentation)
    # ========================================================================
    tta_scales: Tuple[int, ...] = (320, 384, 448)
    tta_hflip: bool = True
    
    # ========================================================================
    # THRESHOLD CALIBRATION
    # ========================================================================
    target_recall: float = 0.95     # Клиник: бараг бүх fracture олох
    
    # ========================================================================
    # MISC
    # ========================================================================
    device: str = 'cuda'
    fp16: bool = True               # Mixed precision (A6000 дээр зөвлөмөл)
    compile: bool = False           # torch.compile (заримдаа EMA-тай зөрчилддөг)
    
    # ========================================================================
    # WANDB
    # ========================================================================
    use_wandb: bool = True
    wandb_project: str = 'fracture-classification'
    wandb_entity: str = None        # Шаардлагатай бол өөрийн username
    
    def __post_init__(self):
        """Хавтас үүсгэх"""
        Path(self.save_dir).mkdir(parents=True, exist_ok=True)
    
    def to_dict(self):
        return asdict(self)
